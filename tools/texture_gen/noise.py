"""Tileable procedural-noise primitives, built for exact seamless wraparound.

Every function here operates in normalized UV space: a texture tile is the
unit square [0, 1) x [0, 1). A field is generated by evaluating noise whose
underlying lattice (value-noise grid cells, Worley feature points) is
periodic with integer period `freq`/`n_cells` across that square, and by
sampling exactly `size` evenly spaced points per axis starting at 0
(`np.linspace(0, freq, size, endpoint=False)`, generalized here to
`freq`-scaled coordinate arrays). Because the lattice repeats after exactly
one unit and the sample grid covers exactly one unit with no aliasing at the
seam, tiling the output N times reproduces the same continuous field with no
visible edge -- there is no offset-and-blend seam hiding involved.

Domain warp stays seamless for the same reason: the warp field itself is
generated by this module (so it is periodic with period 1 in UV space), and
adding a period-1 field to a period-1 coordinate before multiplying by an
integer frequency preserves periodicity exactly.
"""
from __future__ import annotations

import numpy as np
from scipy.ndimage import zoom as _zoom


def quintic(t: np.ndarray) -> np.ndarray:
    """Perlin's improved fade curve: 6t^5 - 15t^4 + 10t^3."""
    return t * t * t * (t * (t * 6.0 - 15.0) + 10.0)


def uv_grid(shape):
    """Pixel-center UV coordinates covering [0, 1) x [0, 1), shape (h, w)."""
    h, w = shape
    y = (np.arange(h, dtype=np.float64) + 0.5) / h
    x = (np.arange(w, dtype=np.float64) + 0.5) / w
    return np.meshgrid(y, x, indexing="ij")


def sample_value_noise(Yc: np.ndarray, Xc: np.ndarray, freq: int, seed: int) -> np.ndarray:
    """Periodic gradient (Perlin-style) noise on a `freq`x`freq` lattice,
    normalized to roughly [0, 1].

    Despite the name (kept for call-site stability), this stores a random
    unit gradient at each lattice point rather than a random scalar, and
    blends the four corners' *directional* contribution with the quintic
    fade. Plain bilinear-interpolated scalar (true "value") noise was tried
    first and visibly showed axis-aligned crease artifacts at low octave
    counts -- an expected property of bilinear interpolation of independent
    corner scalars, since the interpolant's cross second-derivative jumps at
    cell edges. Gradient noise doesn't have that failure mode, which is why
    every other tileable-noise field in this module (`value_noise`, `fbm`,
    `worley`'s warp) is built from this function.

    `Yc`/`Xc` are coordinates already scaled into lattice space (i.e. in
    units of grid cells, not UV) and may be any real number -- indices wrap
    with modulo, so a warped/offset coordinate array stays exactly periodic
    as long as the offset itself was periodic with period `freq` in the same
    units.
    """
    rng = np.random.default_rng(seed)
    angle = rng.random((freq, freq)).astype(np.float64) * (2.0 * np.pi)
    gy = np.sin(angle)
    gx = np.cos(angle)

    yi0 = np.floor(Yc).astype(np.int64)
    xi0 = np.floor(Xc).astype(np.int64)
    yf = Yc - yi0
    xf = Xc - xi0

    yi0m = yi0 % freq
    xi0m = xi0 % freq
    yi1m = (yi0 + 1) % freq
    xi1m = (xi0 + 1) % freq

    def corner_dot(yi, xi, dy, dx):
        return gy[yi, xi] * dy + gx[yi, xi] * dx

    n00 = corner_dot(yi0m, xi0m, yf, xf)
    n10 = corner_dot(yi0m, xi1m, yf, xf - 1.0)
    n01 = corner_dot(yi1m, xi0m, yf - 1.0, xf)
    n11 = corner_dot(yi1m, xi1m, yf - 1.0, xf - 1.0)

    sy = quintic(yf)
    sx = quintic(xf)

    top = n00 * (1.0 - sx) + n10 * sx
    bot = n01 * (1.0 - sx) + n11 * sx
    n = top * (1.0 - sy) + bot * sy
    # Max magnitude of 2D gradient noise is sqrt(2)/2; rescale generously
    # into [0, 1] and clip the rare tail rather than compress the common range.
    return clamp01(n / 0.75 + 0.5)


def value_noise(shape, freq: int, seed: int) -> np.ndarray:
    Y, X = uv_grid(shape)
    return sample_value_noise(Y * freq, X * freq, freq, seed)


def fbm(shape, base_freq: int, octaves: int, seed: int, persistence: float = 0.5,
        lacunarity: int = 2, warp_amp: float = 0.0, warp_freq: int = 2,
        ridged: bool = False) -> np.ndarray:
    """Fractal value noise, normalized to [0, 1], optionally domain-warped.

    `warp_amp`/`warp_freq` add a low-frequency periodic offset (in UV units)
    to the sampling coordinate before each octave, which bends the noise
    into more organic, less grid-aligned shapes without breaking tiling.
    """
    Y, X = uv_grid(shape)

    if warp_amp > 0.0:
        wy = fbm(shape, warp_freq, 2, seed + 9001, persistence=0.5) - 0.5
        wx = fbm(shape, warp_freq, 2, seed + 9002, persistence=0.5) - 0.5
        Y = Y + wy * warp_amp
        X = X + wx * warp_amp

    total = np.zeros(shape, dtype=np.float64)
    amp = 1.0
    amp_sum = 0.0
    freq = base_freq
    for o in range(octaves):
        n = sample_value_noise(Y * freq, X * freq, freq, seed + o * 101)
        if ridged:
            n = 1.0 - np.abs(2.0 * n - 1.0)
        total += amp * n
        amp_sum += amp
        amp *= persistence
        freq = int(round(freq * lacunarity))
    return total / max(amp_sum, 1e-9)


def worley(shape, n_cells: int, seed: int, warp_amp: float = 0.0, warp_freq: int = 3):
    """Periodic Worley/cellular noise: one jittered feature point per cell.

    Returns (f1, f2): distance (in cell units) to the nearest and
    second-nearest feature point. `f2 - f1` gives cell-boundary cracks,
    `f1` gives plate/cobble shading. Exactly tileable: neighbor cells wrap
    with modulo while the feature position used for distance stays in
    unwrapped (possibly negative) cell-space, so distances across the seam
    are correct.
    """
    h, w = shape
    rng = np.random.default_rng(seed)
    jitter = rng.random((n_cells, n_cells, 2))

    ys = np.arange(h, dtype=np.float64) * (n_cells / h) + 0.5 * (n_cells / h)
    xs = np.arange(w, dtype=np.float64) * (n_cells / w) + 0.5 * (n_cells / w)
    Y, X = np.meshgrid(ys, xs, indexing="ij")

    if warp_amp > 0.0:
        # Low-frequency periodic offset, in cell units, breaks the visible
        # regularity of a one-point-per-cell lattice without breaking
        # tiling: the offset is itself periodic with period `n_cells` here
        # because it comes from `fbm` at an integer UV frequency scaled by
        # `n_cells` (see this module's docstring for why that composes).
        wy = (fbm(shape, warp_freq, 2, seed + 7001) - 0.5) * n_cells
        wx = (fbm(shape, warp_freq, 2, seed + 7002) - 0.5) * n_cells
        Y = Y + wy * warp_amp
        X = X + wx * warp_amp

    CI = np.floor(Y).astype(np.int64)
    CJ = np.floor(X).astype(np.int64)

    best1 = np.full(shape, np.inf)
    best2 = np.full(shape, np.inf)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            ni = (CI + dy) % n_cells
            nj = (CJ + dx) % n_cells
            py = (CI + dy).astype(np.float64) + jitter[ni, nj, 0]
            px = (CJ + dx).astype(np.float64) + jitter[ni, nj, 1]
            d2 = (Y - py) ** 2 + (X - px) ** 2
            closer = d2 < best1
            best2 = np.where(closer, best1, np.minimum(best2, d2))
            best1 = np.minimum(best1, d2)
    return np.sqrt(best1), np.sqrt(best2)


def stretch_periodic(field: np.ndarray, factor_y: float = 1.0, factor_x: float = 1.0) -> np.ndarray:
    """Resample a tileable field by (factor_y, factor_x), treating it as
    periodic (`mode='wrap'`) so the result is still exactly seamless.

    Used to build anisotropic/directional features (e.g. water flow
    streaks) out of isotropic noise: generate at a coarser size along the
    axis you want elongated, then stretch back up. Because the source field
    already tiles, wrap-mode resampling introduces no seam.
    """
    out_h = int(round(field.shape[0] * factor_y))
    out_w = int(round(field.shape[1] * factor_x))
    stretched = _zoom(field, (factor_y, factor_x), order=1, mode="wrap")
    return stretched[:out_h, :out_w]


def normalize01(a: np.ndarray) -> np.ndarray:
    lo, hi = a.min(), a.max()
    if hi - lo < 1e-9:
        return np.zeros_like(a)
    return (a - lo) / (hi - lo)


def remap(a: np.ndarray, lo: float, hi: float) -> np.ndarray:
    return lo + normalize01(a) * (hi - lo)


def clamp01(a: np.ndarray) -> np.ndarray:
    return np.clip(a, 0.0, 1.0)


def smoothstep(edge0: float, edge1: float, x: np.ndarray) -> np.ndarray:
    t = clamp01((x - edge0) / max(edge1 - edge0, 1e-9))
    return quintic(t)
